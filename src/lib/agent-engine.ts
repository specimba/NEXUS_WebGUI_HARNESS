export function clip(s: string, n: number): string {
  return s.length <= n ? s : `${s.slice(0, n)}\n…[truncated]`;
}

/** The built-in SDK returns the full completion at once; emit it in small chunks for a live feel. */
export async function simulateStream(text: string, send: EngineSend, signal: AbortSignal): Promise<void> {
  const parts = text.match(/\S+\s*/g) ?? [text];
  let batch = "";
  for (let i = 0; i < parts.length; i++) {
    if (signal.aborted) throw new DOMException("Aborted", "AbortError");
    batch += parts[i];
    if (batch.length >= 24 || i === parts.length - 1) {
      send({ type: "token", text: batch });
      batch = "";
      await sleep(12);
    }
  }
}

export function sleep(ms: number): Promise<void> {
  return new Promise((r) => setTimeout(r, ms));
}

// ─── Region-block detection (r23) ────────────────────────────────────────────
// Datacenter egress IPs are blocked by several providers (Groq/Cerebras/Google
// do it to cloud regions). A 403 there is NOT a key problem — say so honestly
// instead of sending users to re-check a perfectly good key.

const HTML_BLOCK_RE = /<!DOCTYPE html|<!doctype html|<html[\s>]/i;
const CF_BLOCK_RE = /cloudflare|attention required|cf-ray|just a moment|error code: 10\d\d/i;

export function looksLikeRegionBlock(status: number, bodyText: string): boolean {
  if (status !== 403 && status !== 451) return false;
  return HTML_BLOCK_RE.test(bodyText) || CF_BLOCK_RE.test(bodyText) || status === 451;
}

export const REGION_HINT =
  "This provider refuses datacenter IPs (server-region block) — your key is fine. Calls now go browser-direct from your own network; if you still see this, switch provider via the header picker (the relay rotates automatically).";

export function upstreamErrorMessage(status: number, text: string): string {
  // 5xx = the PROVIDER's infrastructure failed (not the user's config) — say
  // so explicitly so diagnostics + retry classification are unambiguous.
  const prefix = status >= 500 ? `Upstream HTTP ${status}: ` : "";
  if (looksLikeRegionBlock(status, text)) {
    return `Provider blocked this network (HTTP ${status}, region/IP block): ${clip(
      text.replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim(),
      120
    )} — ${REGION_HINT}`;
  }
  try {
    const parsed = JSON.parse(text);
    const msg = parsed?.error?.message ?? parsed?.message;
    if (msg) {
      if (status === 401) return `Invalid API key: ${msg}`;
      if (status === 402) return `Out of credits (HTTP 402): ${msg}`;
      if (status === 403) return `Access forbidden (check key/region): ${msg}`;
      if (status === 404) return `Model or endpoint not found: ${msg}`;
      if (status === 429) return `Rate limit exceeded: ${msg}`;
      return `${prefix}${msg}`;
    }
  } catch {
    /* not json */
  }
  return `${prefix}Provider error (HTTP ${status}): ${clip(text || "no details", 300)}`;
}

// ─── Structured error kinds (r25) ────────────────────────────────────────────
// The engine knows WHY a call failed; ship that knowledge with the SSE error
// event so the workflow self-heal stops re-classifying prose by regex (the
// regex stays as a fallback for browser-direct errors).

export type UpstreamErrorKind =
  | "network"
  | "auth"
  | "rate-limit"
  | "timeout"
  | "model"
  | "region"
  | "credits"
  | "unknown";

export function classifyUpstreamError(err: unknown): UpstreamErrorKind {
  const msg = err instanceof Error ? err.message : String(err ?? "");
  if (
    err instanceof UpstreamDeadlineError ||
    /upstream deadline|upstream stalled|no first token|no data for|timed? ?out/i.test(msg)
  ) {
    return "timeout";
  }
  if (/blocked this network|region\/?IP block|datacenter|server-region|\b451\b/i.test(msg)) {
    return "region";
  }
  if (/out of credits|\b402\b|insufficient (?:credits?|funds|balance)|credit.{0,16}(?:exhausted|balance)/i.test(msg)) {
    // r43: 402 is its own kind — "Unknown" hid the single most actionable
    // fact (the lane's account is empty; top up or let the relay step over).
    return "credits";
  }
  if (/\b429\b|rate.?limit|quota|too many requests|capacity is limited/i.test(msg)) {
    // r49: OrcaRouter's free-capacity 429 says "Free model capacity is limited
    // right now. Retry shortly, or add credits…" — no "429"/"rate limit" token
    // anywhere, so it used to fall through to "unknown": no rate-limit
    // step-over, generic recovery card. The provider's own wording is now
    // first-class RATE_LIMITED vocabulary (the state machine's input).
    return "rate-limit";
  }
  if (/\b(401|403)\b|unauthorized|invalid.{0,12}(api )?key|invalid.?key|forbidden|permission denied/i.test(msg)) {
    return "auth";
  }
  if (/\b404\b|no such model|model.?not.?found|model_not_found|endpoint not found|decommissioned|does not exist or is not supported/i.test(msg)) {
    return "model";
  }
  if (/network|fetch failed|failed to fetch|could not reach|socket|econn|enotfound|eai_again|dns|connection (refused|reset|closed|error)|load failed|premature close|stream ended without|upstream|http 5\d\d|bad gateway|service unavailable/i.test(msg)) {
    return "network";
  }
  return "unknown";
}

