/**
 * Model Relay runner: try the primary endpoint, then rotate down body.relay
 * while nothing has streamed to the client. Rotation covers every failure the
 * user cannot fix mid-run — gateway 5xx/network death, 429 rate limits, 402
 * out-of-credits, dead model ids, region blocks — the "Genius rotator"
 * contract: the chain answers even when the head of the chain is having a bad
 * day. Runs identically server-side and browser-direct.
 */
export async function runRelayedCustom(
  body: EngineBody,
  send: EngineSend,
  signal: AbortSignal,
  toolIO: EngineToolIO,
  autoRunner?: AutoRunner
): Promise<void> {
  const primary: RelayWireHop = {
    baseUrl: body.baseUrl,
    apiKey: body.apiKey,
    model: body.model ?? "auto",
    label: body.model ? `primary (${body.model})` : "primary",
    // r25: the primary used to be keyless, so its failures NEVER reached the
    // rotator's health memory and auto-retry kept re-dialing the same dead
    // hop. Stamp it with the same `${providerId}::${model}` convention the
    // wire hops use.
    ...(body.providerId && body.model
      ? { key: `${body.providerId}::${body.model}` }
      : {}),
  };
  const hops = [primary, ...(body.relay ?? [])];
  let clientSawTokens = false;
  const sendGate: EngineSend = (evt) => {
    if (evt.type === "token") clientSawTokens = true;
    send(evt);
  };

  // v0.2 receipt (r26-3): a per-turn safety audit rides toolIO so the tool
  // loops of BOTH engines feed the same record; request_id is generated once
  // and threaded into every fallback hop so one request = one correlation id.
  const audit = toolIO.audit ?? (toolIO.audit = newTurnSafetyAudit());
  const requestId = body.requestId ?? newRequestId();

  let lastErr: unknown = null;
  let autoRetried = false; // r32: one pre-stream retry for the built-in engine
  for (let i = 0; i < hops.length; i++) {
    const hop = hops[i];
    try {
      if (hop.useAuto || !hop.baseUrl) {
        if (!autoRunner) throw new Error("The built-in engine is only available through the app relay");
        await autoRunner({ ...body, baseUrl: undefined, requestId }, sendGate, signal, audit);
      } else {
        await runCustomEngine(
          { ...body, baseUrl: hop.baseUrl, apiKey: hop.apiKey, model: hop.model },
          sendGate,
          signal,
          toolIO
        );
      }
      // A backup hop answered after the primary died — tell the client's
      // health memory so this hop gets promoted next time.
      // r49: [req:…] rides along so the failover event log correlates every
      // attempt of one request end-to-end (the receipt carries the same id).
      if (hop.key) {
        send({ type: "status", message: `Model relay: ${hop.label ?? hop.model} answered ✓ [hopok:${hop.key}][req:${requestId}]` });
      }
      // r27 ROUTE RECEIPT (arXiv:2605.01710): a compact runtime record of the
      // serving path that produced this answer — requested vs resolved model,
      // fallback fact ("no fallback" is information too), coarse reason class.
      // Consumer tier: no internals, no router logic. Client merges tool
      // counts before persisting the receipt on the message.
      send({
        type: "receipt",
        receipt: {
          schema: "route-receipt.v0.1",
          // v0.2 additive fields (r26-3): canonical ids/timestamps + the turn's
          // safety facts. All optional in the type → old receipts stay parseable.
          receipt_id: newRequestId(),
          request_id: requestId,
          served_at: new Date().toISOString(),
          requested_model: body.model ?? "auto",
          resolved_model: hop.model,
          resolved_label: hop.label ?? hop.model,
          model_identifier_type: i === 0 ? "fixed" : "router",
          fallback:
            i === 0
              ? { status: "none" }
              : {
                  status: "occurred",
                  reason: receiptReason(lastErr),
                  from: primary.model,
                  to: hop.model,
                },
          safety: receiptSafety(audit),
          context: { input_truncated: audit.contextTruncated === true },
          tools_allowed: (body.tools ?? []).filter(Boolean),
          tools_used: [],
          completion_status: "complete",
          redactions: [],
        },
      });
      return;
    } catch (err) {
      if (isAbort(err)) throw err;
      lastErr = err;
      // r32: the built-in engine gets ONE retry while nothing has streamed —
      // free-lane 429s and SDK hiccups before the first token are transient.
      // After tokens the honest-error path applies (a re-run would duplicate).
      if (hop.useAuto && !clientSawTokens && !autoRetried && isTransientNetworkError(err)) {
        autoRetried = true;
        send({ type: "status", message: `Built-in engine hiccup (${shortError(err)}) — retrying once…` });
        i -= 1; // re-enter the loop on the same hop
        continue;
      }
      // Mid-stream death: the client already rendered partial output from this
      // hop — rotating now would stitch two models into one answer. Surface it
      // honestly; the step-level self-heal (if any) recovers cleanly.
      // r43: even without rotation the hop's death MUST reach the client's
      // health memory — the [hop:…] marker is what demotes the corpse, and
      // without it every scheduled retry re-dialed the same dead primary first.
      if (clientSawTokens) {
        if (hop.key) {
          send({
            type: "status",
            message: `Model relay: ${hop.label ?? hop.model} died mid-stream (${shortError(err)}) — recorded, no rotation [hop:${hop.key}][req:${requestId}]`,
          });
        }
        throw err;
      }
      if (i === hops.length - 1) {
        // r49: even the chain's death is information — the last hop's failure
        // must reach health memory + the event log (action "exhausted").
        if (hop.key) {
          send({
            type: "status",
            message: `Model relay: chain exhausted — ${hop.label ?? hop.model} was the last lane to fail (${shortError(err)}) [hop:${hop.key}][req:${requestId}][exhausted]`,
          });
        }
        throw err;
      }
      const next = hops[i + 1];
      // [hop:…] marker is consumed by the client's relay health memory — it
      // cools/demotes recently-failed hops in future chains (Genius-rotator
      // memory). [req:…] is the end-to-end correlation id for the event log.
      send({
        type: "status",
        message: `Model relay: ${hop.label ?? hop.model} failed (${shortError(err)}) — rotating to ${next.label ?? next.model}…${hop.key ? ` [hop:${hop.key}]` : ""}[req:${requestId}]`,
      });
    }
  }
  throw lastErr ?? new Error("Relay exhausted with no error");
}

/** Map an upstream failure to the receipt's coarse reason class (no internals). */
function receiptReason(err: unknown): "rate_limit" | "provider_error" | "capacity" | "policy" | "unknown" {
  const kind = classifyUpstreamError(err);
  if (kind === "rate-limit") return "rate_limit";
  if (kind === "region") return "policy";
  if (kind === "auth" || kind === "timeout" || kind === "network" || kind === "model" || kind === "credits") return "provider_error";
  return "unknown";
}

/**
 * v0.2: turn the turn's safety audit into the receipt's canonical safety
 * field. Nothing intervened = "pass"; anything stripped/rejected =
 * "intervened" with a short visible_action (paper §11: record the
 * intervention, never the attack payload). "blocked" is reserved for hard
 * refusals — none of our current defenses emit it.
 */
function receiptSafety(audit: TurnSafetyAudit): RouteReceipt["safety"] {
  if (audit.injectionStrips === 0 && audit.rejectedCalls === 0) {
    return { status: "pass" };
  }
  const actions: string[] = [];
  if (audit.injectionStrips > 0) {
    actions.push(
      `stripped ${audit.injectionStrips} injection pattern${audit.injectionStrips === 1 ? "" : "s"} from tool output`
    );
  }
  if (audit.rejectedCalls > 0) {
    actions.push(
      `rejected ${audit.rejectedCalls} malformed tool call${audit.rejectedCalls === 1 ? "" : "s"}`
    );
  }
  return { status: "intervened", visible_action: actions.join("; ") };
}

function newRequestId(): string {
  return typeof crypto !== "undefined" && "randomUUID" in crypto
    ? crypto.randomUUID()
    : `req-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 10)}`;
}

export async function runCustomEngine(
  body: EngineBody,
  send: EngineSend,
  signal: AbortSignal,
  toolIO: EngineToolIO
): Promise<void> {
  if (body.images?.length) {
    send({ type: "status", message: `Analyzing ${body.images.length} attached image${body.images.length === 1 ? "" : "s"}…` });
  }
  const base = (body.baseUrl || "").replace(/\/+$/, "");
  // Accept both a base URL (…/v1) and a full chat-completions endpoint.
  const url = base.endsWith("/chat/completions") ? base : `${base}/chat/completions`;
  // FIRST-TOKEN budget (r25): OrcaRouter internally fails over 1-5 upstreams
  // before the first byte arrives — give its header→first-byte window a
  // looser deadline than the default.
  let firstTokenMs = FIRST_TOKEN_TIMEOUT_MS;
  try {
    if (new URL(url).host.toLowerCase().includes("orcarouter")) firstTokenMs = FIRST_TOKEN_TIMEOUT_ORCA_MS;
  } catch {
    /* unparseable URL — keep the default budget */
  }
  const model = !body.model || body.model === "auto" ? CUSTOM_FALLBACK_MODEL : body.model;
  const authHeaders: Record<string, string> = body.apiKey
    ? { Authorization: `Bearer ${body.apiKey}` }
    : {};
  const toolIds = (body.tools ?? []).filter(Boolean);
  const maxIterations = clampIter(body.maxIterations);
  const collected: ToolCallInfo[] = [];

  let tools = toolIO.defs.length > 0 ? toolIO.defs : buildToolDefs(toolIds);
  const msgs: Record<string, unknown>[] = [
    { role: "system", content: composeSystem(body.system, tools.length > 0) },
    ...withImages(body.messages, body.images),
  ];

  let graceUsed = 0; // tool-calls salvaged from the FINAL pass (max 2)
  // r34 harness knob: per-turn stall-resume budget (harness “fast” = 1,
  // deep-research/worker = 3, balanced = MAX_STALL_RESUMES).
  const stallResumesMax = Math.max(0, Math.min(3, Math.floor(body.stallResumes ?? MAX_STALL_RESUMES)));
  let stallResumes = 0; // r32: mid-answer stall survivors (max stallResumesMax)
  iterationLoop: for (
    let iteration = 1;
    iteration <= maxIterations + 3 && iteration <= 13;
    iteration++
  ) {
    send({ type: "iteration", n: iteration });
    const isFinalPass = iteration > maxIterations;
    // Resilience (r19): gateways like Vyce sit behind rotating upstream pools
    // and occasionally drop a call mid-run (502/504/socket death) — exactly
    // what killed a Morning-Briefing step after 7 successful tool calls.
    // Retry each LLM call up to 3x while NOTHING has been streamed to the
    // client yet (a mid-stream death can still surface honestly and is
    // recovered one level up by the step-level auto-retry).
    const MAX_UPSTREAM_ATTEMPTS = 3;
    // Parameter adaptation (ModelRelay doctrine): some gateways (Vyce builds)
    // reject the legacy `max_tokens` with "Unknown parameter" and require
    // `max_completion_tokens`. Flip the field on that exact 5xx/4xx signature
    // and retry — the request itself is otherwise identical.
    let maxTokField: "max_tokens" | "max_completion_tokens" = "max_tokens";
    let streamedAny = false;
    let outcome: UpstreamSSEOutcome | null = null;

    attemptLoop: for (let attempt = 1; attempt <= MAX_UPSTREAM_ATTEMPTS; attempt++) {
      // Phase-scoped deadlines (r25): the engine-owned controller carries the
      // FIRST-TOKEN budget (timer below) and the parser enforces the
      // INTER-CHUNK budget; both abort through the same fetch signal a
      // user-cancel uses, but surface as UpstreamDeadlineError so they
      // retry/rotate instead of looking like a user stop. The caller's own
      // abort keeps its original semantics.
      const deadlineCtl = new AbortController();
      const composed = composeAbortSignals(signal, deadlineCtl.signal);
      // FIRST-TOKEN budget (phase A): armed when the upstream fetch STARTS so
      // the silent window is covered even on runtimes whose fetch() only
      // resolves once body bytes flow (Bun — verified by probe). The parser
      // clears it on the first byte of any kind; the deadline fires through
      // deadlineCtl as an UpstreamDeadlineError, never as a user abort.
      let firstTokenTimer: ReturnType<typeof setTimeout> | undefined;
      const clearFirstTokenTimer = () => {
        if (firstTokenTimer) {
          clearTimeout(firstTokenTimer);
          firstTokenTimer = undefined;
        }
      };
      firstTokenTimer = setTimeout(() => {
        deadlineCtl.abort(
          new UpstreamDeadlineError(`upstream deadline: no first token within ${Math.round(firstTokenMs / 1000)}s`)
        );
      }, firstTokenMs);
      let res: Response;
      try {
        res = await fetch(url, {
          method: "POST",
          headers: {
            ...authHeaders,
            "Content-Type": "application/json",
          },
          body: JSON.stringify({
            model,
            messages: msgs,
            temperature: typeof body.temperature === "number" ? body.temperature : 0.7,
            [maxTokField]: body.maxTokens ?? 2048,
            // r35: per-step reasoning effort — only sent when a step asks for
            // it (strict providers reject unknown fields; absent = default).
            ...(body.reasoningEffort ? { reasoning_effort: body.reasoningEffort } : {}),
            stream: true,
            ...(tools.length > 0 && !isFinalPass ? { tools, tool_choice: "auto" } : {}),
          }),
          signal: composed.signal,
        });
      } catch (err) {
        composed.dispose();
        clearFirstTokenTimer();
        // Deadline aborts must not be mistaken for caller aborts (and vice
        // versa): if OUR budget fired, surface the UpstreamDeadlineError even
        // when the runtime rejects fetch with a generic network error — and
        // let it join the pre-stream retry like any other transient hiccup.
        const deadlineReason =
          !signal.aborted && deadlineCtl.signal.aborted && deadlineCtl.signal.reason instanceof UpstreamDeadlineError
            ? (deadlineCtl.signal.reason as UpstreamDeadlineError)
            : null;
        if (isAbort(err) && !deadlineReason) throw err;
        const surfaced: unknown = deadlineReason ?? err;
        if (attempt < MAX_UPSTREAM_ATTEMPTS && !streamedAny && isTransientNetworkError(surfaced)) {
          send({ type: "status", message: `Upstream hiccup (${shortError(surfaced)}) — retrying (${attempt + 1}/${MAX_UPSTREAM_ATTEMPTS})…` });
          await sleep(1200 * attempt);
          continue attemptLoop;
        }
        throw surfaced;
      }

      if (!res.ok || !res.body) {
        composed.dispose();
        clearFirstTokenTimer();
        const text = await res.text().catch(() => "");
        if (res.status === 400 && tools.length > 0 && !isFinalPass && /tool/i.test(text)) {
          send({ type: "status", message: "Model does not support tools — continuing without them" });
          tools = [];
          iteration -= 1; // retry same iteration without tools
          break attemptLoop;
        }
        // Parameter adaptation: gateway rejects `max_tokens` → flip to the
        // newer `max_completion_tokens` name and retry the same attempt.
        if (/unknown parameter[\s\S]{0,20}['"]?max_tokens['"]?/i.test(text)) {
          maxTokField = "max_completion_tokens";
          send({ type: "status", message: "Provider wants max_completion_tokens — adapting…" });
          continue attemptLoop;
        }
        const httpErr = new Error(upstreamErrorMessage(res.status, text));
        if (attempt < MAX_UPSTREAM_ATTEMPTS && isTransientNetworkError(httpErr)) {
          send({ type: "status", message: `Upstream hiccup (${shortError(httpErr)}) — retrying (${attempt + 1}/${MAX_UPSTREAM_ATTEMPTS})…` });
          await sleep(1200 * attempt);
          continue attemptLoop;
        }
        throw httpErr;
      }

      // r34 gateway-router receipt (AIHubMix LLM Router): when the gateway
      // resolved an auto policy it writes the REAL model + decision metadata
      // into x-aihubmix-router-* response headers. Surface it as an SSE event
      // so the reply can show an honest “Router → <model>” chip instead of
      // hiding which brain actually answered behind the "auto" alias.
      const routerResolved = res.headers.get("x-aihubmix-router-resolved-model");
      if (routerResolved) {
        send({
          type: "router",
          resolved: routerResolved.slice(0, 120),
          policy: (res.headers.get("x-aihubmix-router-policy") ?? "").slice(0, 60),
          reason: (res.headers.get("x-aihubmix-router-reason") ?? "").slice(0, 160),
          sticky: res.headers.get("x-aihubmix-router-sticky") === "true",
        });
      }

      try {
        outcome = await consumeUpstreamSSE(
          res.body,
          send,
          signal,
          () => {
            streamedAny = true;
          },
          { ctl: deadlineCtl, clearFirstTokenBudget: clearFirstTokenTimer, idleChunkMs: IDLE_CHUNK_TIMEOUT_MS }
        );
      } catch (err) {
        composed.dispose();
        clearFirstTokenTimer();
        // User aborts keep their original semantics. Everything else that is
        // transient AND pre-stream joins the existing 3x retry — a deadline
        // abort or an in-band error frame before any token is exactly the
        // "provider accepted and then stalled" case these retries exist for.
        if (isAbort(err)) throw err;
        // r32 MID-RUN STALL RESUME: the deadline fired AFTER the answer had
        // begun (tokens streamed / tools executed). Pre-stream retries cannot
        // help and the relay cannot rotate (the client already rendered this
        // hop). Instead of killing the whole turn — which is what wiped a
        // 15-tool research answer at the finish line — keep the executed tool
        // results (they live in msgs) and re-ask for a full self-contained
        // answer. Hard-capped by MAX_STALL_RESUMES.
        const stalledMidRun =
          err instanceof UpstreamDeadlineError && (streamedAny || collected.length > 0);
        if (
          stalledMidRun &&
          stallResumes < stallResumesMax &&
          iteration < maxIterations + 3 &&
          iteration < 13
        ) {
          stallResumes += 1;
          send({
            type: "status",
            message: `Upstream stalled mid-answer — tool findings are intact, finishing the answer (resume ${stallResumes}/${stallResumesMax})…`,
          });
          msgs.push({ role: "user", content: STALL_RESUME_NUDGE });
          continue iterationLoop;
        }
        if (attempt < MAX_UPSTREAM_ATTEMPTS && !streamedAny && isTransientNetworkError(err)) {
          send({ type: "status", message: `Upstream hiccup (${shortError(err)}) — retrying (${attempt + 1}/${MAX_UPSTREAM_ATTEMPTS})…` });
          await sleep(1200 * attempt);
          continue attemptLoop;
        }
        throw err;
      }
      composed.dispose();
      clearFirstTokenTimer();
      break attemptLoop;
    }

    if (!outcome) continue; // tools dropped — replay the same iteration
    const { content, toolCalls, reasoning } = outcome;

    // Some gateways (Pollinations) deliver key-budget notices INSIDE a 200
    // stream as if they were assistant text. Surface them as real errors.
    if (/has reached its budget|raise the key budget/i.test(content)) {
      throw new Error(
        "This provider key has reached its budget — raise the key budget on the provider's dashboard (e.g. enter.pollinations.ai → your key) or switch providers."
      );
    }

    if (toolCalls.length > 0 && tools.length > 0 && !isFinalPass) {
      msgs.push({
        role: "assistant",
        content: content || null,
        ...(toolCalls.length
          ? {
              tool_calls: toolCalls.map((t) => ({
                id: t.id,
                type: "function",
                function: { name: t.name, arguments: t.args || "{}" },
              })),
            }
          : {}),
      });
      for (const tc of toolCalls) {
        send({ type: "status", message: `Using tool: ${tc.name}` });
        send({ type: "tool_call", id: tc.id, name: tc.name, args: tc.args });
        // Closed-world validation (r26): hallucinated tools/argument keys are
        // rejected BEFORE dispatch; the error is fed back as the tool result
        // so the model can self-correct within the same run.
        const validation = validateToolCall(tools, tc.name, tc.args);
        if (!validation.ok && toolIO.audit) toolIO.audit.rejectedCalls += 1;
        const result: ToolResult = validation.ok
          ? await toolIO.execute(tc.name, validation.args ?? "{}", signal)
          : { ok: false, content: validation.error ?? "invalid tool call", ms: 0 };
        collected.push({ id: tc.id, name: tc.name, args: tc.args, result: result.content, ok: result.ok, ms: result.ms });
        send({
          type: "tool_result",
          id: tc.id,
          name: tc.name,
          ok: result.ok,
          ms: result.ms,
          content: clip(result.content, 4000),
        });
        // Provenance fencing (r26): the MODEL sees a scrubbed, fenced copy;
        // the UI keeps the raw content untouched. v0.2: the fence feeds the
        // turn audit (injection strips + context clipping) for the receipt.
        msgs.push({
          role: "tool",
          tool_call_id: tc.id,
          content: clip(fenceToolOutputForModel(tc.name, result.content, 8000, toolIO.audit), 8000),
        });
      }
      if (iteration >= maxIterations) {
        // r29 autonomous synthesis (Temporal/LangGraph "reserve a final pass"
        // doctrine): the LAST in-budget tool round is followed by an explicit
        // synthesis order, so the no-tools final pass is purposeful instead of
        // a silent gamble. This is what turns "budget exhausted + raw dump"
        // into an actual synthesized answer.
        send({ type: "status", message: "Tool budget spent — finalizing answer…" });
        msgs.push({
          role: "user",
          content:
            "TOOL BUDGET SPENT. You have all the material you will get. Write your FINAL markdown answer now, synthesizing the tool results above — plain prose/markdown only, no tool calls, no JSON. If the material is thin or partially failed, say so honestly and answer with what you have.",
        });
      }
      continue;
    }

    // ─── Tool-call-as-text salvage (harness r22) ───────────────────────────
    // Some gateways (Vyce builds) serialize the model's tool call into the
    // CONTENT channel — "web_searchnum<arg_value>10</arg_value>query<arg_value>…"
    // — instead of proper delta.tool_calls. Left alone, that markup becomes
    // the step's "answer" and poisons every downstream step's context. Parse
    // it, execute it, continue the loop like a real tool call.
    if (toolCalls.length === 0 && tools.length > 0) {
      const salvaged = tryParseContentToolCall(content, tools);
      if (salvaged) {
        if (!isFinalPass) {
          send({ type: "status", message: `Model emitted its tool call as text — salvaging: ${salvaged.name}` });
          const id = `salvage_${Math.random().toString(36).slice(2, 10)}`;
          const argsStr = JSON.stringify(salvaged.args);
          msgs.push({ role: "assistant", content });
          send({ type: "status", message: `Using tool: ${salvaged.name}` });
          send({ type: "tool_call", id, name: salvaged.name, args: argsStr });
          // r26: salvage calls pass the same closed-world validation + fencing.
          const validation = validateToolCall(tools, salvaged.name, argsStr);
          if (!validation.ok && toolIO.audit) toolIO.audit.rejectedCalls += 1;
          const result: ToolResult = validation.ok
            ? await toolIO.execute(salvaged.name, validation.args ?? "{}", signal)
            : { ok: false, content: validation.error ?? "invalid tool call", ms: 0 };
          collected.push({ id, name: salvaged.name, args: argsStr, result: result.content, ok: result.ok, ms: result.ms });
          send({ type: "tool_result", id, name: salvaged.name, ok: result.ok, ms: result.ms, content: clip(result.content, 4000) });
          msgs.push({
            role: "user",
            content: `TOOL_RESULT (${salvaged.name}, ok=${result.ok}):\n${clip(fenceToolOutputForModel(salvaged.name, result.content, 8000, toolIO.audit), 8000)}\n\nContinue: use tools if you need more information (call them normally), or give your final markdown answer.`,
          });
          continue;
        }
        // Final-pass leak: execute the salvaged call, grant up to TWO extra
        // synthesis rounds (research models are stubborn — the first grace
        // prompt gets an escalated retry, then the digest fallback fires).
        if (graceUsed < 2 && iteration <= maxIterations + 2) {
          graceUsed += 1;
          send({ type: "status", message: `The model tried another tool call (${salvaged.name}) — running it, then finalizing…` });
          const id = `salvage_${Math.random().toString(36).slice(2, 10)}`;
          const argsStr = JSON.stringify(salvaged.args);
          msgs.push({ role: "assistant", content });
          send({ type: "tool_call", id, name: salvaged.name, args: argsStr });
          // r26: same closed-world validation + fencing on grace rounds.
          const validation = validateToolCall(tools, salvaged.name, argsStr);
          if (!validation.ok && toolIO.audit) toolIO.audit.rejectedCalls += 1;
          const result: ToolResult = validation.ok
            ? await toolIO.execute(salvaged.name, validation.args ?? "{}", signal)
            : { ok: false, content: validation.error ?? "invalid tool call", ms: 0 };
          collected.push({ id, name: salvaged.name, args: argsStr, result: result.content, ok: result.ok, ms: result.ms });
          send({ type: "tool_result", id, name: salvaged.name, ok: result.ok, ms: result.ms, content: clip(result.content, 4000) });
          msgs.push({
            role: "user",
            content:
              graceUsed === 1
                ? `TOOL_RESULT (${salvaged.name}, ok=${result.ok}):\n${clip(fenceToolOutputForModel(salvaged.name, result.content, 8000, toolIO.audit), 8000)}\n\nYour tool budget is now spent. Write your FINAL markdown answer now — plain prose/markdown only, no tool calls of any kind.`
                : `TOOL_RESULT (${salvaged.name}, ok=${result.ok}):\n${clip(fenceToolOutputForModel(salvaged.name, result.content, 8000, toolIO.audit), 8000)}\n\nFINAL WARNING: this is your LAST chance. If you reply with another tool call it will be DISCARDED and the run ends with your research notes only. Write your final markdown answer NOW, synthesizing what you already have — plain prose/markdown only.`,
          });
          send({ type: "status", message: "Finalizing answer…" });
          continue;
        }
      }
    }

    // Cleanup: never let leaked tool-call markup masquerade as the answer.
    const stripped = stripContentToolCall(content);
    // r29 closed the FULL budget-exhaustion family: (1) leaked tool-call
    // markup, (2) degenerate empty finals — a real production run returned
    // the literal string `""` after 36 tool calls, starving every downstream
    // step. Both now fall back to the honest materials digest instead of
    // shipping silence downstream.
    const isSentinel = /^_The model ended/.test(stripped);
    const isTrivialAnswer =
      !isSentinel && collected.length > 0 && /^(["'`\s]*|(null|undefined|nan))$/i.test(stripped.trim());
    const finalContent =
      isSentinel || isTrivialAnswer
        ? `${
            isSentinel
              ? stripped
              : "_The model ended with an empty final answer after its tool rounds — the auto-digest below is what the tools actually gathered. Retry the step for a fuller synthesized answer._"
          }\n\n${buildMaterialsDigest(collected)}`
        : stripped;

    // Honest truncation notice (r25): the stream ended without [DONE] and
    // without a finish_reason — the provider cut the completion short.
    if (outcome.truncated) {
      send({ type: "status", message: "Heads-up: the provider closed this stream early (no end-of-stream marker) — the answer may be cut off." });
    }
    send({ type: "done", content: finalContent, toolCalls: collected, iterations: iteration });
    return;
  }
  throw new Error("Agent loop exceeded maximum iterations.");
}

/** Result of one upstream SSE completion (custom OpenAI-compatible engines). */
export interface UpstreamSSEOutcome {
  content: string;
  toolCalls: UpstreamToolCall[];
  reasoning: string;
  /**
   * True when the stream ended WITHOUT `data: [DONE]` and WITHOUT a
   * finish_reason — the provider cut the completion short (or a gateway ate
   * the tail). Honest signal for the caller; existing fields are unchanged.
   */
  truncated?: boolean;
}

/** Phase-scoped deadline knobs handed to the SSE consumer by the engine. */
export interface UpstreamDeadlineConfig {
  /**
   * Engine-owned abort controller, already wired into the upstream fetch
   * signal. The consumer aborts it when a deadline fires; its `.reason` is
   * the UpstreamDeadlineError so classification never mistakes it for a
   * user stop.
   */
  ctl: AbortController;
  /**
   * Engine → consumer: the FIRST-TOKEN budget lives in the engine (armed when
   * the upstream fetch STARTS — on Bun, fetch() resolves only once body bytes
   * flow, so a headers→first-byte stall would otherwise sit uncovered inside
   * the fetch itself). The consumer calls this the moment ANY byte arrives.
   */
  clearFirstTokenBudget: () => void;
  /** Max gap between bytes once the first byte arrived (ms). */
  idleChunkMs: number;
}

export async function consumeUpstreamSSE(
  body: ReadableStream<Uint8Array>,
  send: EngineSend,
  signal: AbortSignal,
  onFirstChunk?: () => void,
  deadlines?: UpstreamDeadlineConfig
): Promise<UpstreamSSEOutcome> {
  const reader = body.getReader();
  const decoder = new TextDecoder();
  let buffer = "";
  let content = "";
  let reasoning = "";
  let first = true;
  let sawDone = false;
  let sawFinishReason = false;
  const toolCalls: UpstreamToolCall[] = [];

  // ── Phase A: FIRST-TOKEN deadline ─────────────────────────────────────────
  // The timer itself lives in the ENGINE (armed when the upstream fetch
  // starts) and is cleared here the moment ANY byte arrives — content,
  // tool-call deltas AND keep-alive comment lines all count.
  const clearFirstTokenBudget = () => deadlines?.clearFirstTokenBudget();

  // Deterministic translation of a deadline abort into its error: some
  // runtimes surface the abort reason on reader.read(), others throw a bare
  // AbortError — racing every read against this promise covers both. The
  // no-op catch keeps it "handled" when it fires between reads.
  let onDeadlineAbort: (() => void) | undefined;
  const deadlineAborted = deadlines
    ? new Promise<never>((_, reject) => {
        onDeadlineAbort = () => reject(deadlines.ctl.signal.reason ?? new UpstreamDeadlineError("upstream deadline exceeded"));
        deadlines.ctl.signal.addEventListener("abort", onDeadlineAbort, { once: true });
      })
    : null;
  deadlineAborted?.catch(() => {});

  const cancelReader = async () => {
    try {
      await reader.cancel();
    } catch {
      /* ignore */
    }
  };

  /** Parse one SSE line. Throws on in-band error frames (never "content"). */
  const processLine = (raw: string): void => {
    const line = raw.trim();
    // SSE comment / keep-alive lines (`: ping`) carry no data — skip them.
    // (Their bytes still counted as deadline activity in the read loop.)
    if (!line.startsWith("data:")) return;
    const payload = line.slice(5).trim();
    if (payload === "[DONE]") {
      sawDone = true;
      return;
    }
    let chunk: {
      error?: unknown;
      model?: string;
      choices?: Array<{
        finish_reason?: string | null;
        delta?: {
          content?: string;
          reasoning?: string;
          reasoning_content?: string;
          tool_calls?: Array<{ index?: number; id?: string; function?: { name?: string; arguments?: string } }>;
        };
      }>;
    };
    try {
      chunk = JSON.parse(payload);
    } catch {
      return;
    }
    // In-band error frames (OrcaRouter/OpenRouter documented shape:
    // `data: {"error":{...}}`) — fail the stream honestly with the provider's
    // message instead of silently dropping the chunk. Classified as an
    // upstream stream failure ("Upstream …"), never as assistant content.
    if (chunk.error) {
      const msg =
        typeof chunk.error === "string"
          ? chunk.error
          : ((chunk.error as { message?: string })?.message ?? JSON.stringify(chunk.error));
      throw new Error(`Upstream stream error: ${clip(String(msg), 300)}`);
    }
    // Pollinations injects sponsored chunks from a separate "ad-system" model
    // into the same stream — they are not assistant output, drop them.
    if (chunk.model === "ad-system") return;
    const choice = chunk.choices?.[0];
    if (choice?.finish_reason) sawFinishReason = true;
    const delta = choice?.delta;
    if (!delta) return;
    if (delta.reasoning || delta.reasoning_content) {
      const r = delta.reasoning ?? delta.reasoning_content ?? "";
      reasoning += r;
      send({ type: "reasoning", text: r });
    }
    if (delta.content) {
      content += delta.content;
      send({ type: "token", text: delta.content });
    }
    if (delta.tool_calls) {
      for (const tcd of delta.tool_calls) {
        const i = tcd.index ?? 0;
        if (!toolCalls[i]) toolCalls[i] = { id: tcd.id ?? `call_${i}_${Date.now()}`, name: "", args: "" };
        if (tcd.id) toolCalls[i].id = tcd.id;
        if (tcd.function?.name) toolCalls[i].name += tcd.function.name;
        if (tcd.function?.arguments) toolCalls[i].args += tcd.function.arguments;
      }
    }
  };

  try {
    while (true) {
      if (signal.aborted) {
        // Caller/user abort — preserve the original abort semantics exactly.
        await cancelReader();
        throw new DOMException("Aborted", "AbortError");
      }
      const readPromise = reader.read();
      let value: Uint8Array | undefined;
      let done: boolean;
      if (deadlines && deadlineAborted) {
        // Race this read against BOTH deadlines: the first-token budget
        // (phase A) and — once bytes are flowing — the inter-chunk budget
        // (phase B), recreated per read so any gap > idleChunkMs fails.
        let idleTimer: ReturnType<typeof setTimeout> | undefined;
        const idlePromise = first
          ? null
          : new Promise<never>((_, reject) => {
              idleTimer = setTimeout(
                () =>
                  reject(
                    new UpstreamDeadlineError(
                      `upstream stalled: no data for ${Math.round(deadlines.idleChunkMs / 1000)}s`
                    )
                  ),
                deadlines.idleChunkMs
              );
            });
        try {
          const raced = await Promise.race(
            idlePromise ? [readPromise, deadlineAborted, idlePromise] : [readPromise, deadlineAborted]
          );
          value = raced.value;
          done = raced.done;
        } catch (err) {
          if (idleTimer) clearTimeout(idleTimer);
          if (err instanceof UpstreamDeadlineError) {
            deadlines.ctl.abort(err); // make sure the upstream request itself dies
            await cancelReader();
            throw err;
          }
          if (signal.aborted) {
            // caller abort wins — never rebranded as a deadline
            await cancelReader();
            throw isAbort(err) ? err : new DOMException("Aborted", "AbortError");
          }
          const dr = deadlines.ctl.signal.reason;
          if (deadlines.ctl.signal.aborted && dr instanceof UpstreamDeadlineError) throw dr;
          throw err;
        }
        if (idleTimer) clearTimeout(idleTimer);
      } else {
        try {
          const read = await readPromise;
          value = read.value;
          done = read.done;
        } catch (err) {
          if (signal.aborted) {
            await cancelReader();
            throw isAbort(err) ? err : new DOMException("Aborted", "AbortError");
          }
          const dr = deadlines?.ctl.signal.reason;
          if (deadlines?.ctl.signal.aborted && dr instanceof UpstreamDeadlineError) throw dr;
          throw err;
        }
      }
      if (done) break;
      if (first) {
        first = false;
        clearFirstTokenBudget(); // phase A budget consumed by a real byte
        onFirstChunk?.();
      }
      buffer += decoder.decode(value, { stream: true });
      try {
        let idx: number;
        while ((idx = buffer.indexOf("\n")) !== -1) {
          const line = buffer.slice(0, idx);
          buffer = buffer.slice(idx + 1);
          processLine(line);
        }
      } catch (err) {
        // In-band failure — release the upstream connection before failing.
        await cancelReader();
        throw err;
      }
    }
    // Flush the residual line buffer — a final `data: {...}` chunk without a
    // trailing newline used to be discarded (losing the last delta or [DONE]).
    buffer += decoder.decode();
    const residual = buffer;
    buffer = "";
    for (const line of residual.split("\n")) processLine(line);
  } finally {
    clearFirstTokenBudget();
    if (deadlines && onDeadlineAbort) {
      deadlines.ctl.signal.removeEventListener("abort", onDeadlineAbort);
    }
  }

  return {
    content,
    toolCalls: toolCalls.filter(Boolean),
    reasoning,
    // Ended without [DONE] AND without a finish_reason → truncated (r25).
    ...(sawDone || sawFinishReason ? {} : { truncated: true as const }),
  };
}

// ─── Tool-call-as-text salvage parser (harness r22) ──────────────────────────
// Gateways like Vyce sometimes serialize a model's tool call into the CONTENT
// channel instead of delta.tool_calls. Known shapes:
//   1. Mangled arg-tag soup:  "web_searchnum<arg_value>10</arg_value>query<arg_value>…</arg_value>"
//      (tool name immediately followed by bare arg keys + <arg_value> pairs)
//   2. Hermes-style:          "<tool_call>{json}</tool_call>"
//   3. Bare JSON protocol:    {"tool": "web_search", "args": { … }}
function coerceArgValue(v: string): string | number | boolean {
  const t = v.trim();
  if (/^-?\d+(\.\d+)?$/.test(t)) return Number(t);
  if (/^(true|false)$/i.test(t)) return t.toLowerCase() === "true";
  return t;
}

function toolArgsFromJson(j: Record<string, unknown>): Record<string, unknown> | null {
  const raw = (j.args ?? j.arguments ?? j.parameters ?? {}) as unknown;
  if (raw && typeof raw === "object" && !Array.isArray(raw)) return raw as Record<string, unknown>;
  if (typeof raw === "string" && raw.trim().startsWith("{")) {
    try {
      return JSON.parse(raw) as Record<string, unknown>;
    } catch {
      return null;
    }
  }
  return null;
}

function tryJsonObj(s: string): Record<string, unknown> | null {
  try {
    const j = JSON.parse(s) as unknown;
    return j && typeof j === "object" && !Array.isArray(j) ? (j as Record<string, unknown>) : null;
  } catch {
    return null;
  }
}

/**
 * Parse a tool call that leaked into the assistant CONTENT channel.
 * Returns { name, args } when the text unambiguously matches a known tool.
 */
export function tryParseContentToolCall(
  content: string,
  defs: { function: { name: string } }[]
): { name: string; args: Record<string, unknown> } | null {
  const text = content.trim();
  if (!text || text.length > 4000) return null; // long answers are prose, not calls

  // Shape 2 — Hermes-style {json}
  const hermesRe = new RegExp("<" + "tool_call\\s*>\\s*([\\s\\S]+?)\\s*</" + "tool_call\\s*>", "i");
  const hermes = hermesRe.exec(text);
  if (hermes) {
    const j = tryJsonObj(hermes[1]);
    if (j) {
      const name = typeof (j.name ?? j.tool) === "string" ? String(j.name ?? j.tool) : "";
      const args = toolArgsFromJson(j);
      if (name && args && defs.some((d) => d.function.name === name)) return { name, args };
    }
  }

  // Shape 3 — bare JSON protocol object
  if (text.startsWith("{")) {
    const j = tryJsonObj(text);
    if (j && (j.tool || j.name)) {
      const name = String(j.tool ?? j.name);
      const args = toolArgsFromJson(j);
      if (args && defs.some((d) => d.function.name === name)) return { name, args };
    }
  }

  // Shape 1 — mangled arg-tag soup, matched by known tool name prefix:
  // "web_searchnum<arg_value>10</arg_value>query<arg_value>daily AI news …</arg_value>"
  for (const d of defs) {
    const n = d.function.name;
    if (!text.toLowerCase().startsWith(n.toLowerCase())) continue;
    const rest = text.slice(n.length).trim();
    if (!rest) continue;
    if (/<arg_value>/i.test(rest)) {
      const args: Record<string, unknown> = {};
      const pair = /([a-zA-Z_]\w*)\s*<arg_value>([\s\S]*?)<\/arg_value>/gi;
      let pm: RegExpExecArray | null;
      while ((pm = pair.exec(rest))) args[pm[1]] = coerceArgValue(pm[2]);
      if (Object.keys(args).length > 0) return { name: n, args };
    }
    if (rest.startsWith("{")) {
      const j = tryJsonObj(rest);
      if (j) {
        const args = toolArgsFromJson(j) ?? {};
        return { name: n, args };
      }
    }
  }
  return null;
}

/**
 * r29 materials digest — the honest fallback when a step's answer ends up
 * being only leaked tool-call markup. Doctrine (Autonomous-Pipelines r29
 * research): failures are STRUCTURED, not content — the digest body carries
 * only successful results (with arg provenance so downstream steps can
 * re-fetch/cite), while failures collapse into a one-line footer.
 */
export function buildMaterialsDigest(collected: ToolCallInfo[]): string {
  const okCalls = collected.filter((tc) => tc.ok === true);
  const failed = collected.length - okCalls.length;
  const argHead = (tc: ToolCallInfo): string => {
    try {
      const parsed = JSON.parse(tc.args || "{}") as Record<string, unknown>;
      const first = Object.values(parsed).find((v) => typeof v === "string" && v.trim());
      return typeof first === "string" ? clip(first, 80).replace(/\n/g, " ") : "";
    } catch {
      return "";
    }
  };
  const body = okCalls
    .slice(-8)
    .map((tc) => {
      const head = argHead(tc) ? `${tc.name} [${argHead(tc)}]` : tc.name;
      return `- ${head} \u2014 ${clip(tc.result || "(empty result)", 400).replace(/\n+/g, " \u00b7 ")}`;
    })
    .join("\n");
  const footer =
    failed > 0
      ? `\n_${failed} of ${collected.length} tool calls failed and were excluded from this digest._`
      : "";
  if (!body) {
    return `**Research material gathered (auto-digest):**\n_(every tool call failed \u2014 no usable material was gathered)_`;
  }
  return `**Research material gathered (auto-digest):**\n${body}${footer}`;
}

/** Remove leaked tool-call markup from a final answer (never show it as prose). */
export function stripContentToolCall(content: string): string {
  const stripped = content
    .replace(/<arg_(?:key|value)>[\s\S]*?<\/arg_(?:key|value)>/gi, "")
    .replace(/<arg_(?:key|value)[^>]*>/gi, "")
    .replace(new RegExp("<" + "tool_call[\\s\\S]*?</" + "tool_call\\s*>", "gi"), "")
    .replace(new RegExp("<" + "tool_call[^>]*>", "gi"), "")
    .trim();
  if (stripped === content.trim()) return content;
  if (stripped.length === 0) {
    return "_The model ended with another tool call after the tool budget was spent — the auto-digest below is what the tools actually gathered. Retry the step for a fuller synthesized answer._";
  }
  return stripped;
}
