export const MAX_IMAGES = 4;
const MAX_IMAGE_DATAURL_LENGTH = 2_000_000; // ≈1.5 MB binary per image

/** Validate + sanitize the images array (drops non-conforming entries). */
export function sanitizeImages(images: EngineImage[] | undefined): EngineImage[] | undefined {
  if (!Array.isArray(images)) return undefined;
  const ok = images
    .filter(
      (i) =>
        i &&
        typeof i.dataUrl === "string" &&
        i.dataUrl.startsWith("data:image/") &&
        i.dataUrl.length <= MAX_IMAGE_DATAURL_LENGTH
    )
    .slice(0, MAX_IMAGES)
    .map((i, n) => ({ name: typeof i.name === "string" && i.name ? i.name : `image-${n + 1}`, dataUrl: i.dataUrl }));
  return ok.length > 0 ? ok : undefined;
}

/**
 * Convert the last user message into an OpenAI-style multimodal content array
 * (text + image_url parts) when images are attached.
 */
export function withImages(messages: { role: string; content: string }[], images?: EngineImage[]): Record<string, unknown>[] {
  const msgs: Record<string, unknown>[] = messages.map((m) => ({ ...m }));
  if (!images || images.length === 0) return msgs;
  for (let i = msgs.length - 1; i >= 0; i--) {
    if (msgs[i].role === "user") {
      const parts: Record<string, unknown>[] = [{ type: "text", text: String(msgs[i].content ?? "") }];
      for (const img of images) {
        parts.push({ type: "image_url", image_url: { url: img.dataUrl } });
      }
      msgs[i] = { ...msgs[i], content: parts };
      break;
    }
  }
  return msgs;
}

export function isAbort(err: unknown): boolean {
  return (
    (err instanceof Error && (err.name === "AbortError" || err.name === "TimeoutError")) ||
    (err as { code?: string })?.code === "ABORT_ERR"
  );
}

// ─── Phase-scoped upstream deadlines (r25) ───────────────────────────────────
// Providers that accept a request and then stall used to hang the whole run —
// a ~180s silent LLM hang killed a Morning-Briefing step that was otherwise
// 8/8 green. Two budgets cover the two dead phases of an SSE completion:
//   • FIRST TOKEN — headers arrived → first byte (ANY byte counts, including
//     keep-alive comments). OrcaRouter gets a looser budget: it fails over
//     1-5 upstreams internally before the first byte shows up.
//   • INTER-CHUNK — once bytes flow, any gap larger than this fails the call.
// Deadline aborts throw UpstreamDeadlineError so retry/relay classification
// can tell them apart from user aborts (which keep their original semantics).
export class UpstreamDeadlineError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "UpstreamDeadlineError";
  }
}

